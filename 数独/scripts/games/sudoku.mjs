import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { checkBank } from '../build-sudoku-bank.mjs';

async function engineArtifact({ root, output }) {
  const source = (await readFile(path.join(root, 'js', 'sudoku.js'), 'utf8')).replace(/\r\n/g, '\n');
  const exported = [...source.matchAll(/^export\s+(?:const|function)\s+([A-Za-z_$][\w$]*)/gm)].map(match => match[1]);
  assert(exported.length > 0, '未找到可转换的数独引擎导出。');
  assert.equal(new Set(exported).size, exported.length, '数独引擎存在重复导出。');
  // WeChat need not implement Intl.DateTimeFormat. Keep the browser source
  // authoritative and adapt its contemporary Beijing daily calendar here.
  const dailyPattern = /^export function dailySeed\(date = new Date\(\)\) \{[\s\S]*?^\}/m;
  assert(dailyPattern.test(source), 'dailySeed 源码格式已变化，请核对小游戏的北京时间适配。');
  const portableDailySeed = `export function dailySeed(date = new Date()) {
  const timestamp = Number(date);
  if (!Number.isFinite(timestamp)) throw new RangeError('Invalid time value');
  const china = new Date(timestamp + 8 * 60 * 60 * 1000);
  if (!Number.isFinite(china.getTime())) throw new RangeError('Invalid time value');
  const year = china.getUTCFullYear();
  const month = String(china.getUTCMonth() + 1).padStart(2, '0');
  const day = String(china.getUTCDate()).padStart(2, '0');
  return year + '-' + month + '-' + day;
}`;
  const transformed = source.replace(dailyPattern, portableDailySeed).replace(/^export\s+(?=(?:const|function)\s)/gm, '');
  assert(!/^\s*(?:import|export)\b/m.test(transformed), '发现不支持的模块语法，请更新数独构建器。');
  const digest = createHash('sha256').update(source).digest('hex');
  return {
    filename: path.join(output, 'src', 'games', 'sudoku', 'core', 'engine.js'),
    source: `// Generated by scripts/games/sudoku.mjs. Do not edit.\n// Source: js/sudoku.js SHA-256 ${digest}\n'use strict';\n\n${transformed.trimEnd()}\n\nmodule.exports = { ${exported.join(', ')} };\n`,
  };
}

export async function build(context) {
  const engine = await engineArtifact(context);
  await mkdir(path.dirname(engine.filename), { recursive: true });
  await writeFile(engine.filename, engine.source, 'utf8');
  return '数独引擎';
}

export async function check(context) {
  const engine = await engineArtifact(context);
  assert.equal(await readFile(engine.filename, 'utf8'), engine.source, '数独引擎已过期，请先运行 npm run build:wechat。');
  const require = createRequire(import.meta.url);
  const native = require(engine.filename);
  const web = await import(pathToFileURL(path.join(context.root, 'js', 'sudoku.js')));
  assert.deepEqual(Object.keys(native).sort(), Object.keys(web).sort(), '转换后导出与网页引擎不一致。');
  assert.deepEqual(native.DIFFICULTIES, web.DIFFICULTIES);
  let puzzleCount = 0;
  for (const setting of web.DIFFICULTIES) {
    for (const seed of ['wechat-smoke', '2026-10-18', '朋友的同一道题']) {
      const expected = web.generatePuzzle(seed, setting.id);
      const actual = native.generatePuzzle(seed, setting.id);
      assert.deepEqual(actual, expected, `${setting.id}/${seed} 生成结果变化。`);
      assert.equal(native.countSolutions(actual.puzzle), 1);
      assert.deepEqual(native.solve(actual.puzzle), web.solve(expected.puzzle));
      assert.deepEqual(native.getAllCandidates(actual.puzzle), web.getAllCandidates(expected.puzzle));
      assert.deepEqual(native.getConflicts(actual.puzzle), web.getConflicts(expected.puzzle));
      assert.equal(native.isComplete(actual.solution), true);
      puzzleCount += 1;
    }
  }
  const dates = [
    '2024-02-28T15:59:59.999Z', '2024-02-28T16:00:00.000Z',
    '2024-02-29T16:00:00.000Z', '2026-10-17T15:59:59.999Z',
    '2026-10-17T16:00:00.000Z', '2026-12-31T16:00:00.000Z',
  ];
  for (const iso of dates) assert.equal(native.dailySeed(new Date(iso)), web.dailySeed(new Date(iso)), `北京时间日期不一致：${iso}`);
  assert.equal(native.dailySeed(new Date('2026-10-17T16:00:00Z')), '2026-10-18');
  assert.throws(() => native.dailySeed(new Date(NaN)), RangeError);
  const sandbox = { module: { exports: {} }, Intl: undefined };
  vm.runInNewContext(engine.source, sandbox, { filename: engine.filename });
  assert.equal(sandbox.module.exports.dailySeed(new Date('2026-12-31T16:00:00Z')), '2027-01-01');
  const bank = checkBank();
  const bankCount = Object.values(bank.counts).reduce((total, count) => total + count, 0);
  const trainingCount = Object.values(bank.trainingCounts).reduce((total, count) => total + count, 0);
  return `${puzzleCount} 道旧版数独同题、${dates.length} 个日期边界、${bankCount} 道逻辑评级整题、${trainingCount} 张专项卡`;
}

import { readFile, writeFile, readdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { collectMiniGameModules } from './minigame-modules.mjs';
import { checkBackgroundMusic } from './prepare-background-music.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.resolve(root, '..', '微信小程序');
const args = process.argv.slice(2);
const check = args.includes('--check');
const appidArgs = args.filter(value => value.startsWith('--appid='));
if (args.some(value => value !== '--check' && !value.startsWith('--appid=')) || appidArgs.length > 1) {
  throw new Error('用法：node scripts/build-minigame.mjs [--appid=wx0123456789abcdef] 或 --check');
}
const appid = appidArgs[0]?.slice('--appid='.length);
if (appid !== undefined && !/^wx[0-9a-fA-F]{16}$/.test(appid)) {
  throw new Error('AppID 格式应为 wx 加 16 位十六进制字符；请勿填写 AppSecret。');
}
if (check && appid !== undefined) throw new Error('--check 不修改配置；请用构建命令设置 AppID。');

// Games own their source generation and rule checks. A new optional build hook
// is discovered automatically, without editing this project-level orchestrator.
const hookDirectory = path.join(root, 'scripts', 'games');
const hookNames = (await readdir(hookDirectory)).filter(name => name.endsWith('.mjs')).sort();
const hookResults = [];
for (const name of hookNames) {
  const hook = await import(pathToFileURL(path.join(hookDirectory, name)));
  const action = check ? hook.check : hook.build;
  if (typeof action === 'function') {
    const result = await action({ root, output });
    if (result) hookResults.push(result);
  }
}

const entry = "// Generated by scripts/build-minigame.mjs. Do not edit.\nrequire('./src/main.js');\n";
const entryPath = path.join(output, 'game.js');
const configPath = path.join(output, 'project.config.json');
async function readConfig() {
  try { return JSON.parse(await readFile(configPath, 'utf8')); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

if (!check) {
  await writeFile(entryPath, entry, 'utf8');
  const existing = await readConfig();
  const config = existing || {
    description: '游戏之间 · 微信小游戏大厅', miniprogramRoot: './', compileType: 'game',
    appid: 'touristappid', projectname: 'games-between',
    setting: { urlCheck: true, es6: true, minified: true }, simulatorType: 'wechat', condition: {},
  };
  const previousConfig = JSON.stringify(config);
  if (appid !== undefined) config.appid = appid;
  config.packOptions ||= { ignore: [], include: [] };
  config.packOptions.ignore ||= [];
  assert(Array.isArray(config.packOptions.ignore), 'packOptions.ignore 必须为数组。');
  for (const rule of [{ type: 'folder', value: 'vendor' }, { type: 'file', value: 'README.md' }]) {
    if (!config.packOptions.ignore.some(item => item.type === rule.type && item.value === rule.value)) config.packOptions.ignore.push(rule);
  }
  if (!existing || appid !== undefined || JSON.stringify(config) !== previousConfig) {
    await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`, 'utf8');
  }
  console.log(`已生成小游戏入口与游戏产物：${hookResults.join('；')}。`);
  console.log(config.appid === 'touristappid'
    ? '当前为开发导入占位 AppID；正式预览、上传和发布前需要填写自己的小游戏 AppID。'
    : `保留小游戏 AppID：${config.appid}`);
  process.exit(0);
}

assert.equal(await readFile(entryPath, 'utf8'), entry, '小游戏入口已过期，请先运行 npm run build:wechat。');
const config = await readConfig();
assert.equal(config?.compileType, 'game', 'project.config.json 必须使用 compileType: game。');
assert.equal(config?.miniprogramRoot, './', '请以“微信小程序”目录为项目根目录。');
assert(config.appid === 'touristappid' || /^wx[0-9a-fA-F]{16}$/.test(config.appid), '小游戏 AppID 格式无效。');
assert(config.packOptions?.ignore?.some(item => item.type === 'folder' && item.value === 'vendor'), '请排除 vendor 开发源码：先重新运行构建。');
const gameConfig = JSON.parse(await readFile(path.join(output, 'game.json'), 'utf8'));
assert.equal(gameConfig.deviceOrientation, 'portrait');
const packageConfig = JSON.parse(await readFile(path.join(output, 'package.json'), 'utf8'));
assert.equal(packageConfig.type, 'commonjs');
await access(path.join(output, 'src', 'main.js'));
const musicManifest = await checkBackgroundMusic();
// A conservative project budget; this is a raw-file estimate, not a platform upload receipt.
const packageBudget = 4 * 1024 * 1024;
let packageBytes = 0;
async function countPackage(directory, prefix = '') {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix ? prefix + '/' + entry.name : entry.name;
    const ignored = config.packOptions.ignore.some(rule =>
      (rule.type === 'folder' && (relative === rule.value || relative.startsWith(rule.value + '/'))) ||
      (rule.type === 'file' && relative === rule.value));
    if (ignored || relative === 'project.private.config.json' || relative.startsWith('.wechatide/')) continue;
    assert(!entry.isSymbolicLink(), '工程不应打包符号链接：' + relative);
    if (entry.isDirectory()) await countPackage(path.join(directory, entry.name), relative);
    else packageBytes += (await readFile(path.join(directory, entry.name))).length;
  }
}
await countPackage(output);
assert(packageBytes <= packageBudget, '工程文件超出本项目 4 MiB 预算，请压缩或拆分新增资源。');

const modules = await collectMiniGameModules(output);
for (const [id, source] of modules) {
  new vm.Script(source, { filename: id });
  assert(!/\b(?:window|document|localStorage|AudioContext|Phaser)\s*[.(]/.test(source), `原生模块含网页运行时依赖：${id}`);
}
const require = createRequire(import.meta.url);
const { MUSIC_PLAYLIST } = require(path.join(output, 'src', 'platform', 'music.js'));
assert.deepEqual(MUSIC_PLAYLIST.map(track => track.src), musicManifest.tracks.map(track => track.src), '音乐播放列表与资源清单不一致。');
const { GAMES } = require(path.join(output, 'src', 'registry.js'));
const { validateGameModule } = require(path.join(output, 'src', 'app', 'game-contract.js'));
assert(Array.isArray(GAMES) && GAMES.length, '游戏目录不能为空。');
assert.equal(new Set(GAMES.map(game => game.id)).size, GAMES.length, '游戏 ID 不能重复。');
let readyCount = 0;
for (const entry of GAMES) {
  assert(/^[a-z][a-z0-9-]*$/.test(entry.id), `无效游戏 ID：${entry.id}`);
  assert(entry.title && entry.subtitle && entry.icon, `游戏目录缺少展示信息：${entry.id}`);
  assert(['ready', 'soon'].includes(entry.status), `未知游戏状态：${entry.id}`);
  if (entry.status !== 'ready') continue;
  assert.equal(typeof entry.create, 'function', `缺少游戏工厂：${entry.id}`);
  const game = validateGameModule(entry.create({ read: () => null, write: () => true, now: Date.now, services: {} }), entry.id);
  readyCount += 1;
}
require(path.join(output, 'src', 'main.js'));
console.log(`微信小游戏构建检查通过：${hookResults.join('；')}；${modules.length} 个原生模块、${readyCount} 个可运行游戏接口；${musicManifest.tracks.length} 首用户提供背景音乐及来源哈希；工程文件估算 ${(packageBytes / 1024 / 1024).toFixed(2)} MiB（不含已排除文件）。`);
